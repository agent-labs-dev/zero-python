SCHEMA = {
    "tables": {
        "issue": {
            "name": "issue",
            "columns": {
                "id": {"type": "string"},
                "title": {"type": "string", "optional": True},
                "meta": {"type": "json", "optional": True},
                "n": {"type": "number"},
                "ok": {"type": "boolean"},
                "nothing": {"type": "null"},
            },
            "primaryKey": ["id"],
        },
        "class": {"name": "class", "columns": {"from": {"type": "string"}}, "primaryKey": ["from"]},
        "x.y": {"name": "x.y", "columns": {"a-b": {"type": "string"}}, "primaryKey": ["a-b"]},
        "XY": {"name": "XY", "columns": {"id": {"type": "string"}}, "primaryKey": ["id"]},
        "1st": {"name": "1st", "columns": {"id": {"type": "string"}}, "primaryKey": ["id"]},
    },
    "relationships": {},
}


def test_codegen_emits_row_types_and_a_typed_builder() -> None:
    code = generate(load_schema(SCHEMA))
    assert "class Issue(TypedDict):\n    id: str\n    title: str | None\n    meta: Any\n" in code
    assert "class IssueInsert(TypedDict):\n    id: str\n    title: NotRequired[str | None]\n" in code
    assert "class IssueUpdate(TypedDict):\n    id: str\n    title: NotRequired[str | None]\n" in code
    assert "    n: float\n    ok: bool\n    nothing: None\n" in code
    assert 'type IssueColumn = Literal["id", "title", "meta", "n", "ok", "nothing"]' in code
    # Keys that are not identifiers fall back to the functional syntax; such tables get no property.
    assert 'Class = TypedDict("Class", {"from": str})' in code
    assert 'XY = TypedDict("XY", {"a-b": str})' in code
    assert "class XY_(TypedDict):" in code
    assert "class Table1st(TypedDict):" in code
    assert "def issue(self) -> Query[Issue, IssueColumn]:" in code
    assert "def XY(self) -> Query[XY_, XY_Column]:" in code
    assert "def class(" not in code
    namespace: dict[str, Any] = {}
    exec(compile(code, "zero_schema.py", "exec"), namespace)
    zql = namespace["create_builder"](load_schema(SCHEMA))
    assert zql.issue.where("title", "x").ast.where is not None
    assert namespace["mutate"].__doc__


def test_codegen_handles_an_empty_schema() -> None:
    code = generate(load_schema({"tables": {}}))
    assert "class Builder(_Builder):\n    pass\n" in code
    assert "class Mutate(Protocol):\n    pass\n" in code


def test_codegen_cli(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    schema = tmp_path / "schema.json"
    schema.write_text(json.dumps(SCHEMA))
    assert main(["codegen", str(schema)]) == 0
    assert "Generated by `zero-server codegen`" in capsys.readouterr().out
    out = tmp_path / "zero_schema.py"
    assert main(["codegen", str(schema), "-o", str(out)]) == 0
    assert out.read_text() == generate(load_schema(SCHEMA), "schema.json")


def test_strict_builder_refuses_unknown_columns() -> None:
    zql = create_builder(load_schema(SCHEMA), strict=True)
    for build in (
        lambda: zql.issue.where("nope", 1),
        lambda: zql.issue.where(lambda eb: eb.cmp("nope", 1)),
        lambda: zql.issue.order_by("nope", "asc"),
        lambda: zql.issue.start({"nope": 1}),
    ):
        with pytest.raises(UnknownColumnError, match='unknown column "nope" of "issue" table'):
            build()
    assert zql.issue.where("title", "x").order_by("n", "desc").start({"n": 1}).ast.start is not None
    assert create_builder(load_schema(SCHEMA)).issue.where("nope", 1).ast.where is not None


def test_one_keeps_its_type_and_shows_its_ast() -> None:
    query = create_builder(load_schema(SCHEMA)).issue.one().where("id", "a")
    assert isinstance(query, OneQuery)
    assert query.format.singular
    assert repr(create_builder(load_schema(SCHEMA)).issue) == "Query({'table': 'issue'})"


class Args(BaseModel):
    id: str


async def test_decorator_forms() -> None:
    zql = create_builder(load_schema(SCHEMA))

    @define_query(Args)
    def by_id(*, args: Args, ctx: Any) -> Any:
        return zql.issue.where("id", args.id)

    @define_query
    def everything(*, args: Any, ctx: Any) -> Any:
        return zql.issue

    seen: list[Any] = []

    @define_mutator(Args)
    async def touch(*, tx: Any, ctx: Any, args: Args) -> None:
        seen.append(args.id)

    @define_mutator
    async def noop(*, tx: Any, ctx: Any, args: Any) -> None:
        seen.append(args)

    queries = define_queries({"byID": by_id, "all": everything})
    assert queries.byID.fn(args={"id": "a"}).ast.where is not None
    assert queries.all.fn().ast.table == "issue"
    mutators = define_mutators({"touch": touch, "noop": noop})
    await mutators.touch.fn(args={"id": "b"}, tx=None)
    await mutators.noop.fn(args=1, tx=None)
    assert seen == ["b", 1]


class RecordingDatabase:
    """Runs callbacks against nothing, answering the bookkeeping hooks in memory."""

    def __init__(self) -> None:
        self.last_mutation_id = 0

    async def transaction(self, callback: Any, transaction_input: Any = None) -> Any:
        database = self

        class Hooks:
            async def update_client_mutation_id(self) -> int:
                database.last_mutation_id += 1
                return database.last_mutation_id

            async def write_mutation_result(self, result: Any) -> None:
                return None

            async def delete_mutation_results(self, args: Any) -> None:
                return None

        return await callback("tx", Hooks())


def _app(**overrides: Any) -> tuple[TestClient, list[Any]]:
    schema = load_schema(SCHEMA)
    zql = create_builder(schema)
    seen: list[Any] = []

    @define_mutator
    async def record(*, tx: Any, ctx: Any, args: Any) -> None:
        seen.append((tx, ctx, args))

    async def authenticate(request: Request) -> str | None:
        token = request.headers.get("authorization")
        if token == "Bearer bad":
            raise Unauthorized
        return token

    options: dict[str, Any] = {
        "schema": schema,
        "database": RecordingDatabase(),
        "queries": define_queries({"all": define_query(lambda *, args, ctx: zql.issue.where("id", ctx["userID"]))}),
        "mutators": define_mutators({"record": record}),
        "authenticate": authenticate,
        **overrides,
    }
    return TestClient(Starlette(routes=zero_routes(**options))), seen


PUSH = {
    "clientGroupID": "g",
    "pushVersion": 1,
    "timestamp": 1,
    "requestID": "r",
    "mutations": [{"type": "custom", "id": 1, "clientID": "c", "name": "record", "args": [5], "timestamp": 1}],
}


def test_routes_answer_queries_and_mutations() -> None:
    client, seen = _app()
    query = client.post(
        "/query", json=["transform", [{"id": "1", "name": "all", "args": []}]], headers={"authorization": "u"}
    )
    assert query.json()["userID"] == "u"
    assert query.json()["queries"][0]["ast"]["where"]["right"] == {"type": "literal", "value": "u"}
    mutate = client.post("/mutate?schema=zero_0&appID=zero", json=PUSH, headers={"authorization": "u"})
    assert mutate.json() == {
        "kind": "MutateResponse",
        "userID": "u",
        "mutations": [{"id": {"id": 1, "clientID": "c"}, "result": {}}],
    }
    assert seen == [("tx", {"userID": "u"}, 5)]


def test_routes_refuse_rejected_tokens() -> None:
    client, _ = _app()
    for path in ("/query", "/mutate"):
        response = client.post(path, json=[], headers={"authorization": "Bearer bad"})
        assert (response.status_code, response.json()) == (401, {"error": "Unauthorized"})


async def _async_context(request: Request, user_id: str | None) -> dict[str, Any]:
    return {"userID": user_id, "path": request.url.path}


def test_routes_take_async_context_and_custom_paths() -> None:
    client, seen = _app(context=_async_context, query_path="/q", mutate_path="/m", authenticate=lambda _r: "sync")
    assert client.post("/q", json=["transform", []]).json()["userID"] == "sync"
    client.post("/m?schema=zero_0&appID=zero", json=PUSH)
    assert seen == [("tx", {"userID": "sync", "path": "/m"}, 5)]


def test_routes_only_for_what_is_given() -> None:
    assert [r.path for r in zero_routes(schema=load_schema(SCHEMA), authenticate=lambda _r: None)] == []
    with pytest.raises(ValueError, match="needs a database"):
        zero_routes(schema=load_schema(SCHEMA), mutators=define_mutators({}), authenticate=lambda _r: None)


def test_builder_reuses_a_query_built_from_the_same_object() -> None:
    """A value of no JSON type, which only Python code passes, is keyed by its identity."""
    zql = create_builder(load_schema(json.dumps(SCHEMA)))
    value, other = object(), object()
    assert zql.issue.where("meta", value) is zql.issue.where("meta", value)
    assert zql.issue.where("meta", value) is not zql.issue.where("meta", other)
