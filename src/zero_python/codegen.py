"""Typed Python for a Zero schema: row types per table, and a builder and `tx.mutate` that use them.

    zero-python codegen schema.json -o zero_schema.py

`schema.json` is `JSON.stringify(schema)` of the TypeScript `schema.ts`. The generated module has, per
table, a `TypedDict` for a row (`Issue`), for an insert (`IssueInsert`, optional columns may be left
out), for an update (`IssueUpdate`, the key plus any columns) and for a delete (`IssueKey`), and a
`Literal` of its column names (`IssueColumn`). Its `create_builder` returns queries typed by those rows
and columns, and `mutate(tx)` is `tx.mutate` typed the same way. Rows of a `related()` relationship
come back nested under each row but are not part of the row type.
"""

import argparse
import json
import keyword
import re
import sys
from pathlib import Path

from zero_python.schema import ColumnSchema, Schema, TableSchema, load_schema

_TYPES = {"string": "str", "number": "float", "boolean": "bool", "null": "None", "json": "Any"}


def _class_name(table: str) -> str:
    parts = re.split(r"[^0-9A-Za-z]+", table)
    name = "".join(part[:1].upper() + part[1:] for part in parts if part)
    if not name or name[0].isdigit():
        name = f"Table{name}"
    return name


def _is_identifier(name: str) -> bool:
    return name.isidentifier() and not keyword.iskeyword(name)


def _value_type(column: ColumnSchema) -> str:
    base = _TYPES[column.type]
    return f"{base} | None" if column.optional and base not in ("Any", "None") else base


def _typed_dict(name: str, fields: list[tuple[str, str, bool]]) -> str:
    """A TypedDict, in class syntax when every key is an identifier, else in functional syntax.

    Never empty: every table has a primary key, which all four row types include.
    """
    if all(_is_identifier(key) for key, _, _ in fields):
        lines = [f"    {key}: {f'NotRequired[{t}]' if not required else t}" for key, t, required in fields]
        return f"class {name}(TypedDict):\n" + "\n".join(lines) + "\n"
    items = ", ".join(f"{json.dumps(key)}: {f'NotRequired[{t}]' if not required else t}" for key, t, required in fields)
    return f"{name} = TypedDict({json.dumps(name)}, {{{items}}})\n"


def _table(name: str, table: TableSchema, used: set[str]) -> tuple[str, str]:
    """The table's type definitions, and the class name they were given."""
    cls = _class_name(name)
    while cls in used:
        cls += "_"
    used.add(cls)
    pk = set(table.primary_key)
    columns = list(table.columns.items())
    row = [(c, _value_type(s), True) for c, s in columns]
    insert = [(c, _value_type(s), c in pk or not s.optional) for c, s in columns]
    update = [(c, _value_type(s), c in pk) for c, s in columns]
    key = [(c, _value_type(table.columns[c]), True) for c in table.primary_key]
    column_names = ", ".join(json.dumps(c) for c, _ in columns)
    out = [
        f"type {cls}Column = Literal[{column_names}]\n",
        _typed_dict(cls, row),
        _typed_dict(f"{cls}Insert", insert),
        _typed_dict(f"{cls}Update", update),
        _typed_dict(f"{cls}Key", key),
    ]
    return "\n\n".join(out), cls


def generate(schema: Schema, source: str = "schema.json") -> str:
    used: set[str] = set()
    definitions: list[str] = []
    builder: list[str] = []
    mutate: list[str] = []
    for name, table in schema.tables.items():
        types, cls = _table(name, table, used)
        definitions.append(types)
        if _is_identifier(name):
            builder.append(
                f"    @property\n    def {name}(self) -> Query[{cls}, {cls}Column]:\n"
                f"        return self.table({json.dumps(name)})\n"
            )
            crud = f"TableCRUD[{cls}Insert, {cls}Update, {cls}Key]"
            mutate.append(f"    @property\n    def {name}(self) -> {crud}: ...\n")
    header = f'''"""Types for the Zero schema in {source}. Generated by `zero-python codegen`; do not edit."""

from typing import Any, Literal, NotRequired, Protocol, TypedDict, cast

from zero_python.query.builder import Builder as _Builder
from zero_python.query.builder import Query
from zero_python.schema import Schema
from zero_python.server.crud import TableCRUD
from zero_python.server.transaction import ServerTransaction
'''
    body = "\n\n".join(definitions)
    builder_class = "class Builder(_Builder):\n" + ("\n".join(builder) if builder else "    pass\n")
    mutate_class = "class Mutate(Protocol):\n" + ("\n".join(mutate) if mutate else "    pass\n")
    footer = '''def create_builder(schema: Schema, *, strict: bool = False) -> Builder:
    return Builder(schema, strict=strict)


def mutate(tx: ServerTransaction[Any]) -> Mutate:
    """`tx.mutate`, typed by this schema."""
    return cast(Mutate, tx.mutate)
'''
    # One blank line after the imports, two between definitions: what ruff's formatter and isort keep.
    return header + "\n" + "\n\n".join([body, builder_class, mutate_class, footer]).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="zero-python")
    commands = parser.add_subparsers(dest="command", required=True)
    codegen = commands.add_parser("codegen", help="generate Python types for a schema")
    codegen.add_argument("schema", type=Path, help="the JSON of the TypeScript schema")
    codegen.add_argument("-o", "--output", type=Path, help="write here instead of to stdout")
    args = parser.parse_args(argv)
    code = generate(load_schema(args.schema), args.schema.name)
    if args.output is None:
        sys.stdout.write(code)
    else:
        args.output.write_text(code)
    return 0


if __name__ == "__main__":  # pragma: no cover - the `zero-python` script calls `main` directly
    sys.exit(main())
